"""Build the bilingual training dataset (Phase 5, task 3).

    python -m member4_chatbot.dataset.build

Inputs: data/processed/passages.csv, data/docs/raw/*.txt (fertilizer tables), and the hand-written sources in
data/training/sources/ (intents.yaml, ai_drafted_en.yaml, ai_drafted_si.yaml, ai_drafted_intents.yaml,
ai_drafted_refusals.yaml, nllb_translations.csv).

NONE of the questions is written or checked by a person: they are generated by code (templates, paraphrases),
drafted by the AI coding assistant, or machine-translated. Every row has checked_by_human = "no" until a team
member reviews it. The CSVs say so in the `source` and `author` columns (see SOURCE_LABELS).

Outputs in data/training/:
- intents.csv       every question with its intent (the intent classifier's data)
- qa_pairs.csv      questions that a passage answers, with a 1-3 sentence answer (the retriever's data)
- out_of_scope.csv  the questions the bot must refuse
- dataset_stats.json, and the numbers in DATASET.md
All three CSVs have a `split` column. The split is by passage: every question about one passage (and its
other-language twin) lands in the same split; questions without a passage are grouped with their own
paraphrases and translations. Fixed seed.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
from collections import Counter, defaultdict

import pandas as pd
import yaml

from member4_chatbot.dataset.paraphrase import paraphrase
from member4_chatbot.dataset.templates import all_template_pairs
from member4_chatbot.lang import detect_language
from member4_chatbot.paths import PASSAGES_CSV, RAW_DOCS_DIR, TRAINING_DIR, TRAINING_SOURCES_DIR

SEED = 20261018
SPLIT_FRACTIONS = {"train": 0.70, "val": 0.15, "test": 0.15}
QA_COLUMNS = ["id", "question", "answer", "lang", "answer_lang", "intent", "passage_id", "also_correct", "split",
              "source", "author", "template", "checked_by_human", "group_id"]
INTENT_COLUMNS = ["id", "text", "lang", "intent", "split", "source", "author", "checked_by_human", "group_id",
                  "passage_id"]
OOS_COLUMNS = ["id", "text", "lang", "category", "split", "source", "author", "checked_by_human", "group_id"]
# Internal source keys (used in the stable row ids, so splits never change) -> what the CSVs show.
SOURCE_LABELS = {
    "template": ("auto_template", "code: templates over DOA/RRDI tables"),
    "handwritten": ("ai_drafted", "AI coding assistant (Claude Code)"),
    "handwritten_si": ("ai_drafted", "AI coding assistant (Claude Code)"),
    "intent_only": ("ai_drafted", "AI coding assistant (Claude Code)"),
    "out_of_scope": ("ai_drafted", "AI coding assistant (Claude Code)"),
    "paraphrase": ("auto_paraphrase", "code: rule-based paraphrase of an AI-drafted question"),
    "nllb": ("machine_translated", "NLLB-200-distilled-600M (local) from an AI-drafted question"),
}


def load_yaml(name: str):
    return yaml.safe_load((TRAINING_SOURCES_DIR / name).read_text(encoding="utf-8"))


def row_id(*parts: str) -> str:
    return hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:12]


class PassageIndex:
    def __init__(self, passages: pd.DataFrame):
        self.by_doc = {d: g for d, g in passages.groupby("doc")}

    def resolve(self, doc: str, anchor: str) -> str:
        g = self.by_doc.get(doc)
        if g is None:
            raise KeyError(f"unknown doc {doc!r}")
        hit = g[g.text.str.contains(anchor, case=False, regex=True)]
        if hit.empty:
            raise KeyError(f"anchor {anchor!r} not found in {doc}")
        return hit.id.iloc[0]


def checked(flag) -> str:
    return "yes" if str(flag).lower() in ("yes", "true") else "no"


def base_rows(passages: pd.DataFrame) -> tuple[list[dict], list[str]]:
    """All rows before paraphrasing and translation, plus a list of anchor errors."""
    idx = PassageIndex(passages)
    rows, errors = [], []

    def qa_row(q, a, lang, intent, pid, also, source, template, chk):
        return {"question": q, "answer": a, "lang": lang, "answer_lang": "si" if detect_language(a) == "si" else "en",
                "intent": intent, "passage_id": pid, "also_correct": ";".join(also), "source": source,
                "template": template, "checked_by_human": chk}

    for p in all_template_pairs(RAW_DOCS_DIR, passages, SEED):
        try:
            pid = idx.resolve(p.doc, p.anchor)
        except KeyError as e:
            errors.append(f"template {p.template}: {e}")
            continue
        also = []
        for d, a in p.also:  # the other-language page may lack this field; then it is simply not listed
            try:
                also.append(idx.resolve(d, a))
            except KeyError:
                pass
        rows.append(qa_row(p.question, p.answer, p.lang, p.intent, pid, also, "template", p.template, "no"))

    for fname, source in (("ai_drafted_en.yaml", "handwritten"), ("ai_drafted_si.yaml", "handwritten_si")):
        for item in load_yaml(fname)["items"]:
            try:
                pid = idx.resolve(item["doc"], re.escape(str(item["anchor"])))
            except KeyError as e:
                errors.append(f"{fname}: {e}")
                continue
            for qa in item["qa"]:
                lang = "si" if source == "handwritten_si" else "en"
                rows.append(qa_row(qa["q"], qa["a"], lang, item["intent"], pid, [], source, "",
                                   checked(qa.get("checked", item.get("checked")))))

    for intent, by_lang in load_yaml("ai_drafted_intents.yaml").items():
        for lang, qs in by_lang.items():
            for q in qs:
                rows.append({"question": q, "answer": "", "lang": lang, "answer_lang": "", "intent": intent,
                             "passage_id": "", "also_correct": "", "source": "intent_only", "template": "",
                             "checked_by_human": "no"})

    for category, by_lang in load_yaml("ai_drafted_refusals.yaml").items():
        for lang, qs in by_lang.items():
            for q in qs:
                rows.append({"question": q, "answer": "", "lang": lang, "answer_lang": "", "intent": "out_of_scope",
                             "passage_id": "", "also_correct": "", "source": "out_of_scope", "template": category,
                             "checked_by_human": "no"})
    for r in rows:
        r["id"] = row_id(r["source"], r["lang"], r["question"])
        r["origin_id"] = r["id"]
    return rows, errors


def translatable(rows: list[dict]) -> list[dict]:
    """English rows written by people (not templates, not paraphrases) get a machine-translated Sinhala copy."""
    return [r for r in rows if r["lang"] == "en" and r["source"] in ("handwritten", "intent_only", "out_of_scope")]


def texts_to_translate() -> list[str]:
    passages = pd.read_csv(PASSAGES_CSV, keep_default_na=False)
    rows, _ = base_rows(passages)
    out = []
    for r in translatable(rows):
        out.append(r["question"])
        if r["answer"]:
            out.append(r["answer"])
    return out


def derived_rows(rows: list[dict], translations: dict[str, str], rng: random.Random) -> list[dict]:
    out = []
    for r in rows:
        if r["lang"] == "en" and r["source"] in ("handwritten", "intent_only", "out_of_scope"):
            p = paraphrase(r["question"], rng)
            if p:
                d = dict(r, question=p, source="paraphrase", checked_by_human="no")
                d["id"] = row_id("paraphrase", "en", p, r["id"])
                out.append(d)
    for r in translatable(rows):
        q = translations.get(r["question"])
        if not q:
            continue
        a = translations.get(r["answer"], "") if r["answer"] else ""
        d = dict(r, question=q, answer=a, lang="si", answer_lang="si" if a else "", source="nllb",
                 checked_by_human="no")
        d["id"] = row_id("nllb", "si", q, r["id"])
        out.append(d)
    return out


def assign_groups(rows: list[dict]) -> None:
    """group_id: passages linked by also_correct form one group (union-find); rows without a passage are grouped
    with their own paraphrases and translations (same origin_id)."""
    parent: dict[str, str] = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for r in rows:
        if r["passage_id"]:
            for other in filter(None, r["also_correct"].split(";")):
                parent[find(other)] = find(r["passage_id"])
    for r in rows:
        r["group_id"] = "p:" + find(r["passage_id"]) if r["passage_id"] else "q:" + r["origin_id"]


def assign_splits(rows: list[dict], seed: int = SEED) -> None:
    """Greedy group split: groups in seeded random order; each goes to the split furthest below its target share
    of the group's main intent. Deterministic for a fixed seed."""
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        groups[r["group_id"]].append(r)
    keys = sorted(groups)
    random.Random(seed).shuffle(keys)
    intent_total = Counter(r["intent"] for r in rows)
    have: dict[str, Counter] = defaultdict(Counter)
    for k in keys:
        g = groups[k]
        intent = Counter(r["intent"] for r in g).most_common(1)[0][0]
        deficit = {s: frac * intent_total[intent] - have[intent][s] for s, frac in SPLIT_FRACTIONS.items()}
        split = max(SPLIT_FRACTIONS, key=lambda s: (deficit[s], s == "train"))
        have[intent][split] += len(g)
        for r in g:
            r["split"] = split


def main() -> dict:
    passages = pd.read_csv(PASSAGES_CSV, keep_default_na=False)
    rows, errors = base_rows(passages)
    if errors:
        raise SystemExit("Anchors that match no passage (fix the source files):\n  " + "\n  ".join(errors))
    from member4_chatbot.dataset.translate import load_cache, translate_missing

    need = [t for r in translatable(rows) for t in (r["question"], r["answer"]) if t]
    from member4_chatbot.dataset.translate import repair_zwj, sinhala_vocabulary

    vocab = sinhala_vocabulary(passages[passages.lang == "si"].text.tolist()
                               + [(TRAINING_SOURCES_DIR / "ai_drafted_si.yaml").read_text(encoding="utf-8")])
    translations = {k: repair_zwj(v, vocab) for k, v in translate_missing(need).items()}
    rng = random.Random(SEED)
    rows += derived_rows(rows, translations, rng)

    # translations marked checked in the cache count as human-checked
    cache = load_cache()
    checked_tr = set(cache[cache.checked.str.lower() == "yes"].translation)
    for r in rows:
        if r["source"] == "nllb" and r["question"] in checked_tr:
            r["checked_by_human"] = "yes"

    # drop exact duplicate questions (same text and language), keeping the first
    seen, unique = set(), []
    for r in rows:
        key = (r["lang"], r["question"].strip().lower())
        if key not in seen:
            seen.add(key)
            unique.append(r)
    rows = unique
    assign_groups(rows)
    assign_splits(rows)

    TRAINING_DIR.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(rows)
    df["author"] = df.source.map(lambda s: SOURCE_LABELS[s][1])
    df["source"] = df.source.map(lambda s: SOURCE_LABELS[s][0])
    qa = df[df.passage_id != ""][QA_COLUMNS]
    intents = df.rename(columns={"question": "text"})[INTENT_COLUMNS]
    oos = df[df.intent == "out_of_scope"].rename(columns={"question": "text", "template": "category"})
    oos = oos[OOS_COLUMNS]
    qa.to_csv(TRAINING_DIR / "qa_pairs.csv", index=False, encoding="utf-8")
    intents.to_csv(TRAINING_DIR / "intents.csv", index=False, encoding="utf-8")
    oos.to_csv(TRAINING_DIR / "out_of_scope.csv", index=False, encoding="utf-8")

    stats = dataset_stats(df, qa, oos)
    (TRAINING_DIR / "dataset_stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False), encoding="utf-8")
    from member4_chatbot.dataset.report import write_dataset_md

    write_dataset_md(stats)
    print(f"{len(df)} question rows ({stats['share_sinhala_script']:.1%} Sinhala script); "
          f"{len(qa)} QA pairs; {len(oos)} out-of-scope; intents min {min(stats['by_intent'].values())}")
    return stats


def dataset_stats(df: pd.DataFrame, qa: pd.DataFrame, oos: pd.DataFrame) -> dict:
    def ct(frame, *cols):
        return {"|".join(map(str, k)) if isinstance(k, tuple) else str(k): int(v)
                for k, v in frame.groupby(list(cols)).size().items()}

    return {
        "seed": SEED,
        "total_questions": int(len(df)),
        "share_sinhala_script": float((df.lang == "si").mean()),
        "share_sinhala_incl_singlish": float(df.lang.isin(["si", "si_latn"]).mean()),
        "by_lang": ct(df, "lang"),
        "by_intent": ct(df, "intent"),
        "by_intent_lang": ct(df, "intent", "lang"),
        "by_split": ct(df, "split"),
        "by_split_lang": ct(df, "split", "lang"),
        "by_intent_split": ct(df, "intent", "split"),
        "by_source": ct(df, "source"),
        "by_source_lang": ct(df, "source", "lang"),
        "checked_by_human": ct(df, "checked_by_human"),
        "qa_pairs": int(len(qa)),
        "qa_by_split_lang": ct(qa, "split", "lang"),
        "qa_passages": int(qa.passage_id.nunique()),
        "qa_passages_by_split": {s: int(g.passage_id.nunique()) for s, g in qa.groupby("split")},
        "out_of_scope": int(len(oos)),
        "oos_by_category": ct(oos, "category"),
        "oos_by_split": ct(oos, "split"),
        "template_kinds": ct(df[df.source == "auto_template"], "template"),
        "by_author": ct(df, "author"),
    }


if __name__ == "__main__":
    main()
